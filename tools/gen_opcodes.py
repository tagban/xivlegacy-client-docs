#!/usr/bin/env python3
"""Build docs/opcodes.md from three sources:

  data/xivl_opcode_names.json   XIVLegacy xivl-captures opcode catalog (CC BY 4.0): service,
                                direction, name, retail handler class, confidence
  data/garlemald_opcodes.json   opcode constants from Garlemald's map-server/src/packets/opcodes.rs
                                (refresh with --garlemald <path to opcodes.rs>)
  data/observed_opcodes.json    how often each opcode appeared in our own server's packet logs

Usage: gen_opcodes.py [--garlemald path/to/opcodes.rs]
"""

import argparse
import collections
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"


def extract_garlemald(path):
    """[{name, opcode, section, doc}] from opcodes.rs: each `pub const OP_*: u16 = 0x....;` with
    its `///` doc comment (first sentence) and the `// ----` section it sits under."""
    out, doc, section = [], [], ""
    lines = Path(path).read_text().splitlines()
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith("// ---") and i + 1 < len(lines) and lines[i + 1].startswith("// "):
            section = lines[i + 1][3:].split("(")[0].split(".")[0].strip()
        if s.startswith("///"):
            doc.append(s[3:].strip())
            continue
        m = re.match(r"pub const (OP_[A-Z0-9_]+): u16 = (0x[0-9A-Fa-f]+);", s)
        if m:
            text = " ".join(doc)
            first = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0] if text else ""
            out.append({"name": m[1], "opcode": int(m[2], 16), "section": section, "doc": first[:160]})
        if not s.startswith("///"):
            doc = []
    return out


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--garlemald", help="path to Garlemald map-server/src/packets/opcodes.rs")
    args = ap.parse_args()
    if args.garlemald:
        json.dump(extract_garlemald(args.garlemald), open(DATA / "garlemald_opcodes.json", "w"), indent=1)

    xivl = json.load(open(DATA / "xivl_opcode_names.json"))["entries"]
    garl = json.load(open(DATA / "garlemald_opcodes.json"))
    seen = json.load(open(DATA / "observed_opcodes.json"))

    garl_by_op = collections.defaultdict(list)
    for g in garl:
        garl_by_op[g["opcode"]].append(g)
    seen_by = {(e["service"], e["direction"], e["opcode"]): e["count"] for e in seen}

    rows = collections.defaultdict(dict)  # (service, direction) -> opcode -> row
    for e in xivl:
        op = int(e["opcodeHex"], 16)
        rows[(e["service"], e["direction"])][op] = {
            "xivl": e["name"], "cls": e.get("retail_class_name") or "", "conf": e.get("confidence") or ""}
    for (svc, d, op), n in seen_by.items():
        rows[(svc, d)].setdefault(op, {"xivl": "", "cls": "", "conf": ""})

    order = [("map", "clientbound"), ("map", "serverbound"), ("world", "clientbound"),
             ("world", "serverbound"), ("lobby", "clientbound"), ("lobby", "serverbound"),
             ("world_map_backend", "backend")]
    titles = {"clientbound": "server → client", "serverbound": "client → server", "backend": "world ↔ map server"}

    md = ["# Opcode reference", "",
          "Game-message opcodes for the 1.23b protocol. Generated by `tools/gen_opcodes.py`; do not edit by hand.", "",
          "Columns:", "",
          "- **Opcode**: the 16-bit opcode in the game-message header (subpacket type 3).",
          "- **Name**: the name in the XIVLegacy xivl-captures catalog.",
          "- **Garlemald**: the matching constant(s) in Garlemald's `opcodes.rs` (matched by number only; "
          "the same number can mean different things per service and direction).",
          "- **Retail handler**: the client-side class that routes it, from the catalog.",
          "- **Confidence**: the catalog's evidence level (`confirmed`, `implemented`, `pcap_observed`, "
          "`decomp_routed`, `blocked`).",
          "- **Seen**: how many times it appeared in our own server's packet logs (map and world servers).",
          "",
          "Packet framing is described in [protocol.md](protocol.md).", ""]
    for key in order:
        if key not in rows:
            continue
        svc, d = key
        md += [f"## {svc} — {titles[d]}", "",
               "| Opcode | Name | Garlemald | Retail handler | Confidence | Seen |",
               "| --- | --- | --- | --- | --- | --- |"]
        for op in sorted(rows[key]):
            r = rows[key][op]
            g = garl_by_op.get(op, [])
            gtxt = "<br>".join(f"`{x['name']}`" + (f" — {esc(x['doc'])}" if x["doc"] else "") for x in g[:3])
            n = seen_by.get((svc, d, op), "")
            md.append(f"| `0x{op:04X}` | {esc(r['xivl'])} | {gtxt} | {esc(r['cls'])} | {r['conf']} | {n} |")
        md.append("")
    md += ["## Sources", "",
           "- Opcode catalog: [XIVLegacy/xivl-captures](https://github.com/XIVLegacy/xivl-captures) "
           "`derived/opcode_names.json`, CC BY 4.0, by the XIVLegacy Dev Team (a separate project).",
           "- Constants: [Garlemald-Server](https://github.com/swstegall/Garlemald-Server) "
           "`map-server/src/packets/opcodes.rs` (AGPL-3.0; names only).",
           "- Counts: our local server's packet logs.", ""]
    (ROOT / "docs" / "opcodes.md").write_text("\n".join(md))
    print("rows:", sum(len(v) for v in rows.values()))


if __name__ == "__main__":
    main()
